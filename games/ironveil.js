function stepTo(en, pl, avoidTypes) {
  var dx = pl.x - en.x;
  var dy = pl.y - en.y;
  var nx, ny;

  function isPlayer(x, y) {
    return x === pl.x && y === pl.y;
  }

  if (Math.abs(dx) >= Math.abs(dy)) {
    nx = en.x + (dx > 0 ? 1 : -1);
    if (!isSolid(nx, en.y, avoidTypes) && !isPlayer(nx, en.y)) { en.x = nx; return; }
    if (dy !== 0) {
      ny = en.y + (dy > 0 ? 1 : -1);
      if (!isSolid(en.x, ny, avoidTypes) && !isPlayer(en.x, ny)) en.y = ny;
    }
  } else {
    ny = en.y + (dy > 0 ? 1 : -1);
    if (!isSolid(en.x, ny, avoidTypes) && !isPlayer(en.x, ny)) { en.y = ny; return; }
    if (dx !== 0) {
      nx = en.x + (dx > 0 ? 1 : -1);
      if (!isSolid(nx, en.y, avoidTypes) && !isPlayer(nx, en.y)) en.x = nx;
    }
  }
}

